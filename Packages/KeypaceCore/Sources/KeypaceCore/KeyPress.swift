import Foundation

/// One key press. The character it produced is used only to classify it and is never kept.
public struct KeyPress: Sendable, Equatable {
    /// Transient word-boundary information; contains no typed text.
    public enum TextCategory: Sendable, Equatable {
        case word, whitespace, separator, joiner, symbol
    }

    public enum Kind: Sendable, Equatable {
        /// Produced text: letters, digits, punctuation, Space, Return, Tab.
        case character
        /// Delete, removing one character.
        case backspace
        /// Option-Delete, removing the word before the cursor.
        case deleteWord
        /// Command-Delete; visual line length is unknown, so this is treated as editing.
        case deleteLine
        /// Navigation, function keys, shortcuts and dead keys.
        case other
    }

    /// Seconds on a monotonic clock.
    public var time: Double
    public var keyCode: UInt16
    public var kind: Kind
    public var textCategory: TextCategory
    /// True for events generated by holding a key down.
    public var isRepeat: Bool

    public init(time: Double, keyCode: UInt16, kind: Kind, isRepeat: Bool = false, textCategory: TextCategory? = nil) {
        self.time = time
        self.keyCode = keyCode
        self.kind = kind
        self.isRepeat = isRepeat
        // Raw presses without text metadata assume a word character, except the known whitespace keys.
        self.textCategory = textCategory ?? ([36, 48, 49].contains(keyCode) ? .whitespace : .word)
    }
}

public enum KeyClassifier {
    public static let backspaceKeyCode: UInt16 = 51

    /// Classifies the produced text under its actual layout, then discards it.
    public static func textCategory(_ text: String) -> KeyPress.TextCategory {
        if !text.isEmpty, text.unicodeScalars.allSatisfy({ CharacterSet.whitespacesAndNewlines.contains($0) }) {
            return .whitespace
        }
        if text == "'" || text == "’" || text == "." { return .joiner }
        if !text.isEmpty, text.unicodeScalars.allSatisfy({ CharacterSet.symbols.contains($0) }) {
            return .symbol
        }
        if text == "_" || (!text.isEmpty && text.unicodeScalars.allSatisfy({
            CharacterSet.alphanumerics.contains($0) || CharacterSet.nonBaseCharacters.contains($0)
        })) {
            return .word
        }
        return .separator
    }

    /// - Parameters:
    ///   - commandOrControl: Command or Control is held; shortcuts aren't typing.
    ///   - command: Command specifically, which turns Delete into a line delete.
    ///   - option: Option, which turns Delete into a word delete.
    ///   - text: what the key produced under the active layout; empty for dead keys.
    public static func kind(keyCode: UInt16, commandOrControl: Bool, command: Bool = false, option: Bool = false, text: String) -> KeyPress.Kind {
        if keyCode == backspaceKeyCode {
            if command { return .deleteLine }
            if commandOrControl { return .other }
            return option ? .deleteWord : .backspace
        }
        if commandOrControl { return .other }
        guard !text.isEmpty else { return .other }
        for scalar in text.unicodeScalars {
            switch scalar.value {
            case 0x09, 0x0A, 0x0D: continue // Tab, newline, Return
            case 0x00...0x1F, 0x7F: return .other // Escape and other control characters
            case 0xF700...0xF8FF: return .other // AppKit function-key range: arrows, F-keys, Home, End
            default: continue
            }
        }
        return .character
    }
}
